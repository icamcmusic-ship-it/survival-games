/**
 * A regular expression that matches a chronicle line produced from `template`
 * for any tribute and zone. Achievements use it so they never restate prose.
 */
export function lineMatcher(template: string): RegExp {
    const escape = (part: string) => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return new RegExp(`^${template.split(/\{tribute\}|\{zone\}/).map(escape).join('.+?')}$`);
}
