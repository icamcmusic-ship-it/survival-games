/** Scales the lethal half of the file, as group 6 does with its own knobs. */
function tuned(events: ArenaEventDef[], weightScale: number): ArenaEventDef[] {
    return events.map(e => (e.damage ?? 0) > 0
        ? {
            ...e,
            weight: (e.weight ?? 1) * weightScale,
            damage: Math.round(e.damage! * AUDIT12_EVENTS.damageScale),
            dodgeDifficulty: (e.dodgeDifficulty ?? ENCOUNTERS.defaultDodgeDifficulty) + AUDIT12_EVENTS.dodgeDifficultyBonus,
        }
        : e);
}

