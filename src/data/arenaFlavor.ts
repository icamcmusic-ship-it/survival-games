/**
 * Arena-specific colour: every arena gets its own hazards, its own idle
 * actions, and its own ambient broadcast lines, so the Frozen Wasteland never
 * reads like the Solar Desert with the nouns swapped.
 *
 * Templates support {tribute}, {zone} and (for forage lines) {item}.
 */

export interface ArenaEventDef {
    /** What happens when the tribute fails to avoid it. */
    text: string;
    /** What the feed says when they slip out of it. */
    escapeText: string;
    /** Cause of death recorded if this kills them. */
    cause: string;
    /** Attribute rolled against to avoid the event entirely. */
    dodgeStat?: keyof Attributes;
    /**
     * A second way out, rolled at a penalty when the primary fails. Left unset
     * on almost every event: heavy physical hazards fall back to strength
     * automatically. See `rollEscape` in `engine/encounters.ts`.
     */
    dodgeAlt?: keyof Attributes;
    /** Flat difficulty of the dodge (higher = harder). Default 6. */
    dodgeDifficulty?: number;
    damage?: number;
    bleeding?: boolean;
    poisoned?: boolean;
    burned?: boolean;
    frostbitten?: boolean;
    infected?: boolean;
    sanity?: number;
    thirst?: number;
    hunger?: number;
    fatigue?: number;
    /** Positive outcomes exist too — not every arena event is a punishment. */
    heal?: number;
    quench?: number;
    feed?: number;
    /** Item id granted by the event, if any. */
    grantItem?: string;
    /**
     * Which terrains this can plausibly happen on. Undefined means "anywhere",
     * which is what every hand-authored event defaulted to before this field
     * existed — a tribute standing on Glacier Peak could trigger "Thin Ice
     * Collapse" on solid rock a thousand feet up. Left optional rather than
     * back-filled across every event by hand; `encounters.ts` falls back to a
     * keyword guess from `cause`/`text` for events that don't set it.
     */
    terrains?: Terrain[];
    /** Hits everyone standing in the zone, not just the tribute who triggered it. */
    zoneWide?: boolean;
    /** Leaves the zone itself in this state for a while — see `ZoneEffect`. */
    startsZoneEffect?: ZoneEffectKind;
    /** Severs one of the zone's adjacency edges — a bridge going out. */
    severesRoute?: boolean;
    /**
     * §1.3: relative draw weight. Defaults to 1 for a hand-authored arena
     * event; the shared universal pool is merged in at `UNIVERSAL_EVENT_WEIGHT`
     * so an arena with five authored events does not read as generic three
     * times out of four.
     */
    weight?: number;
    /**
     * §7e: stable identity, needed by anything that has to refer to a specific
     * event later — `oncePerRun` bookkeeping and `chain`. Optional: the great
     * majority of events are anonymous and stay that way.
     */
    id?: string;
    /** §7e: fires at most once in a run. Requires `id`. */
    oncePerRun?: boolean;
    /**
     * §7e: preconditions on arena *state* rather than on terrain alone, so an
     * event can be written for "this zone is already on fire", "after dark",
     * "when the field is down to six" or "only under this law".
     */
    requires?: {
        effect?: ZoneEffectKind;
        time?: 'day' | 'night';
        minSurvivors?: number;
        maxSurvivors?: number;
        law?: ArenaLawId;
    };
    /** §7e: id of the event this one leads to, fired on the same tribute next cycle. */
    chain?: string;
    /** §7e: names everyone who saw it, whether or not the event itself touched them. */
    witnesses?: boolean;
}

export interface ArenaActions {
    forage: string[];
    rest: string[];
    hide: string[];
    hunt: string[];
    travel: string[];
    /**
     * A1: one pool per conditional stance.
     *
     * Optional, and resolved through `actionPool()` rather than read directly,
     * so the twenty-eight hand-authored arenas keep working unchanged and pick
     * up the terrain-general fallbacks below until somebody writes them a
     * bespoke set. An arena that *does* author them wins; nothing silently
     * prints an empty string.
     */
    fortify?: string[];
    scavenge?: string[];
    shadow?: string[];
    flail?: string[];
}

/** The keys `actionPool` will fall back on. */
export type ArenaActionKey = keyof ArenaActions;

export interface ArenaFlavor {
    /** Broadcast-style scene setting, fired occasionally with no tribute attached. */
    ambient: string[];
    actions: ArenaActions;
    events: ArenaEventDef[];
}

